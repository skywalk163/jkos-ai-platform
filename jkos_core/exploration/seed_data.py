async def seed_knowledge_base(kb: KnowledgeBase) -> int:
    """把种子数据写入知识库（幂等：已有 >= 60 条时跳过），返回写入条数"""
    await kb.initialize()
    expected = len(SEED_SOLUTIONS) + len(SEED_FAILURES)
    if await kb.count() >= expected:
        return 0
    written = 0
    for item in SEED_SOLUTIONS:
        await kb.store(
            Solution(
                solution_id=f"seed-{written:03d}",
                task=str(item["task"]),
                steps=[str(s) for s in item["steps"]],
                source_type="knowledge",
                result_summary=str(item["summary"]),
            ),
            Result(task=str(item["task"]), success=True,
                   summary=str(item["summary"])),
        )
        written += 1
    for item in SEED_FAILURES:
        await kb.store_failure(
            Solution(solution_id=f"seedf-{written:03d}",
                     task=str(item["task"]), steps=[str(item["task"])],
                     source_type="knowledge"),
            str(item["error"]),
        )
        written += 1
    return written